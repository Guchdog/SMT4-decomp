// The ledger label/signature is misleading: this entry ignores r0-r2 and
// updates the map-interface talk-target list. The 128 records at work+0x1d0
// have the 0x194-byte stride also documented by ui::TalkWork. The code below
// is a semantic draft for the globally evidenced prefix of the routine; the
// 20-state per-record handler and later UI/render side effects remain open.
[[maybe_unused]] static void FlowScript_ProcessFlagBank_Draft() {
    auto* const work = reinterpret_cast<smt4::ui::TalkWork*>(
        smt4::engine::g_MapIfWork);
    auto* const event_state = smt4::engine::g_MapRuntimeState;
    auto* const scene = smt4::engine::g_MapSceneView;
    auto* const camera = g_ScriptCameraWork;

    // 0x001e5d9c..0x001e5dfc: a busy byte at event-state +0x18 starts the
    // map-interface transition timer at work+0xcce4; otherwise it counts down
    // and clears/sets the transition-active byte at work+0xcce0.
    if (event_state[0x18] != 0) {
        smt4::engine::g_MapIfWork->field_cce0 = 1;
        smt4::engine::g_MapIfWork->field_cce4 = 2;
    } else if (smt4::engine::g_MapIfWork->field_cce4 <= 0) {
        smt4::engine::g_MapIfWork->field_cce4 = 0;
        smt4::engine::g_MapIfWork->field_cce0 = 0;
    } else {
        --smt4::engine::g_MapIfWork->field_cce4;
        smt4::engine::g_MapIfWork->field_cce0 = 1;
    }

    const auto distance3 = [](const f32* a, const f32* b) -> f32 {
        const f32 dx = b[0] - a[0];
        const f32 dy = b[1] - a[1];
        const f32 dz = b[2] - a[2];
        return std::sqrt(dx * dx + dy * dy + dz * dz);
    };

    // The first distance gate uses ScriptCameraWork's blended eye/target
    // vectors (+0x4c/+0x58). If their separation is at least 1.0, the routine
    // refreshes each active target's distance to the live scene position.
    if (distance3(camera->blend_eye, camera->blend_target) >= 1.0f) {
        const f32* const scene_position = &scene->field_01c;
        for (u32 i = 0; i < 0x80; ++i) {
            auto& entry = work->entries[i];
            if (entry.active_000 == 0) {
                continue;
            }
            auto* const bytes = reinterpret_cast<u8*>(&entry);
            auto* const target_position =
                reinterpret_cast<f32*>(bytes + 0x5c);
            *reinterpret_cast<f32*>(bytes + 0x48) =
                distance3(scene_position, target_position);
            bytes[0x4c] = 0;              // clear the per-frame winner marker
        }

        // Group active entries by positive key at +0x1c. The binary marks the
        // whole group visited and retains the member with the greatest +0x48
        // distance; its byte at +0x4c becomes the selected representative.
        u8 visited[0x80] = {};
        for (u32 i = 0; i < 0x80; ++i) {
            auto* const first = reinterpret_cast<u8*>(&work->entries[i]);
            if (first[0] == 0 || visited[i] != 0) {
                continue;
            }
            const s32 key = *reinterpret_cast<s32*>(first + 0x1c);
            if (key <= 0) {
                continue;
            }

            u32 winner = i;
            visited[i] = 1;
            for (u32 j = i + 1; j < 0x80; ++j) {
                auto* const candidate =
                    reinterpret_cast<u8*>(&work->entries[j]);
                if (candidate[0] == 0 ||
                    *reinterpret_cast<s32*>(candidate + 0x1c) != key) {
                    continue;
                }
                visited[j] = 1;
                const f32 candidate_distance =
                    *reinterpret_cast<f32*>(candidate + 0x48);
                auto* const incumbent =
                    reinterpret_cast<u8*>(&work->entries[winner]);
                if (candidate_distance >
                    *reinterpret_cast<f32*>(incumbent + 0x48)) {
                    winner = j;
                }
            }
            reinterpret_cast<u8*>(&work->entries[winner])[0x4c] = 1;
        }
    }

    // 0x001e61a0..0x001e61d4 dispatches each active record's +4 state through
    // a 20-entry table (states 0..0x13); every arm has additional camera,
    // event, UI, and timer effects. The remaining per-record states and
    // output synchronization are intentionally not approximated here.
}

